#!/usr/bin/env python3
"""Generate native vector widget skins from the player palettes."""
from pathlib import Path


def build(root, theme, p):
    directory = root / theme / 'images'
    def svg(name, w, h, body):
        (directory / (name + '.svg')).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" preserveAspectRatio="none">{body}</svg>\n')
    def panel(name, fill, stroke, w=160, h=36):
        r = min(p['radius'], 8)
        svg(name, w, h, f'<rect x=".5" y=".5" width="{w-1}" height="{h-1}" rx="{r}" fill="{fill}" stroke="{stroke}"/>')
    panel('ui_button', p['top'], p['edge'])
    panel('ui_hover', p['well'], p['accent'])
    panel('ui_pressed', p['bottom'], p['accent'])
    panel('ui_menu', p['bottom'], p['edge'], 240, 240)
    panel('ui_search', p['well'], p['edge'], 600, 40)
    for active in (False, True):
        svg('button_menu_on' if active else 'button_menu', 20, 20,
            f'<rect x="1.5" y="1.5" width="17" height="17" rx="4" fill="{p["accent_light"] if active else p["well"]}" stroke="{p["accent"] if active else p["edge"]}"/>'
            f'<path d="M6 6.5h8M6 10h8M6 13.5h8" fill="none" stroke="{p["shade"] if active else p["ink"]}" stroke-width="1.2" stroke-linecap="round"/>')
    # Broad, quiet framing with a different signature for each instrument.
    motifs = {
        'default': '<path d="M620 29h100m-100 5h72m-72 5h44"/>',
        'gant': '<path d="M622 24h18v20h-18zm24 0h18v20h-18zm24 0h18v20h-18zm24 0h18v20h-18z"/>',
        'nocturne': '<path d="M630 40q10-32 20 0t20 0t20 0t20 0"/>',
        'folio': '<circle cx="680" cy="34" r="24"/><circle cx="680" cy="34" r="17"/><circle cx="680" cy="34" r="5"/><path d="M714 16l-6 28"/>',
        'frequency': '<path d="M610 40h120M620 40V24m10 16v-8m10 8V24m10 16v-8m10 8V24m10 16v-8m10 8V24m10 16v-8m10 8V24m10 16v-8m10 8V24"/>',
        'voltage': '<path d="M610 40h26l8-24 12 35 12-28 8 17h42l12-12"/>',
        'undertow': '<path d="M608 27q24-18 48 0t48 0t48 0m-144 10q24-18 48 0t48 0t48 0m-144 10q24-18 48 0t48 0t48 0"/>',
    }
    svg('ui_editor', 780, 66,
        f'<rect width="780" height="520" fill="{p["bottom"]}"/>'
        f'<path d="M0 0h780v66H0Z" fill="{p["top"]}"/>'
        f'<path d="M22 65h736" stroke="{p["edge"]}"/>'
        f'<path d="M22 65h64" stroke="{p["accent"]}" stroke-width="2"/>'
        f'<g fill="none" stroke="{p["accent"]}" stroke-width="1.3">{motifs[theme]}</g>')
    svg('ui_about', 480, 128,
        f'<path d="M24 64h104m224 0h104" stroke="{p["edge"]}"/>'
        f'<circle cx="240" cy="64" r="58" fill="{p["well"]}" stroke="{p["edge"]}"/>'
        f'<circle cx="240" cy="64" r="50" fill="none" stroke="{p["accent"]}" opacity=".5"/>'
        f'<path d="M144 61v6m192-6v6M237 2h6m-6 124h6" stroke="{p["accent"]}"/>'
        f'<g transform="translate(-440 30)" fill="none" stroke="{p["accent"]}" '
        f'stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">{motifs[theme]}</g>')
    for state in ('off', 'on'):
        svg('ui_check_' + state, 22, 22,
            f'<rect x="2.5" y="2.5" width="17" height="17" rx="4" fill="{p["well"]}" stroke="{p["accent"] if state == "on" else p["edge"]}"/>' +
            (f'<path d="m6 11 3 3 7-7" fill="none" stroke="{p["accent"]}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>' if state == 'on' else ''))
    icons = {
        'help-about': 'M12 10v7m0-11v1M22 12a10 10 0 1 1-20 0 10 10 0 0 1 20 0',
        'folder-open': 'M3 7V4h7l3 3h8v13H3Zm0 3h18',
        'view-list-details': 'M8 5h13M8 12h13M8 19h13M3 5h1M3 12h1M3 19h1',
        'window-new': 'M3 4h18v16H3ZM3 8h18M6 6h1',
        'preferences-desktop-theme': 'M12 3 3 8l9 5 9-5ZM3 12l9 5 9-5M3 16l9 5 9-5',
        'document-open': 'M5 3h9l5 5v13H5ZM14 3v6h5M8 14h8m-8 3h6',
        'document-save': 'M4 3h14l3 3v15H3V3ZM7 3v6h9V3M7 21v-8h10v8',
        'list-add': 'M4 12h16M12 4v16',
        'list-remove': 'M4 12h16',
        'edit-select-all': 'M3 3h18v18H3ZM7 12l3 3 7-7',
        'edit-clear': 'M5 5l14 14M19 5 5 19',
        'edit-delete': 'M4 6h16M9 6V3h6v3M6 6l1 15h10l1-15M10 10v7m4-7v7',
        'media-playlist-shuffle': 'M3 5h3l12 14h3m-4-4 4 4-4 3M3 19h3l4-5m4-5 4-4h3m-4-3 4 3-4 4',
        'media-playlist-repeat': 'M4 9V5h15m-4-4 4 4-4 4M20 15v4H5m4-4-4 4 4 4',
        'edit-find': 'M16 16l6 6M18 10a8 8 0 1 1-16 0 8 8 0 0 1 16 0',
        'arrow': 'm9 5 7 7-7 7',
    }
    for name, path in icons.items():
        svg('ui_icon_' + name, 24, 24, f'<path d="{path}" fill="none" stroke="{p["ink"]}" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/>')
    rgb = lambda key: ' '.join(str(int(p[key][i:i+2],16)) for i in (1,3,5)) + ' 255'
    generated = '/* Generated by tools/theme-dialogs.py via theme-vectors.py. */\n'
    for key in ('ink','edge','well','accent','bottom'):
        generated += f'#define UI_{key.upper()} {rgb(key)}\n'
    generated += f'#define UI_INK_HEX "{p["ink"]}ff"\n'
    generated += f'#define UI_ENTRY_STYLE "font=Sans font_size=11 color={p["ink"]}ff wrap=none"\n'
    generated += f'#define UI_LABEL_STYLE "font=Sans font_size=10 color={p["ink"]}ff wrap=word"\n'
    generated += '#include "../../common/dialogs.edc"\n'
    for name in icons:
        generated += f'group {{ name: "eclair/icon/{name}"; min: 18 18; parts {{ part {{ name: "icon"; type: VECTOR; mouse_events: 0; description {{ state: "default" 0.0; image.normal: "ui_icon_{name}.svg"; }} }} }} }}\n'
    (root / theme / 'groups/dialogs.edc').write_text(generated)
